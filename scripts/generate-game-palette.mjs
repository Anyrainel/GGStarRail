import { readFile, writeFile } from "node:fs/promises";
import {
  COMBAT_TYPE_HEADER_RGB,
  COMBAT_TYPE_RGB,
  ITEM_TOKENS,
  RARITY_GRADIENTS,
  RARITY_TOKENS,
  TIER_COLORS,
} from "../src/config/gameColors.ts";

const target = new URL("../src/generated/game-palette.css", import.meta.url);
const colors = [];
function color(name, value) {
  colors.push(`  --color-${name}: ${value};`);
}
for (const [id, rgb] of Object.entries(COMBAT_TYPE_RGB)) {
  color(`combat-${id.toLowerCase()}`, `rgb(${rgb.join(" ")})`);
  color(
    `combat-${id.toLowerCase()}-header`,
    `rgb(${COMBAT_TYPE_HEADER_RGB[id].join(" ")})`
  );
}
for (const [id, values] of Object.entries(TIER_COLORS)) {
  color(`tier-${id.toLowerCase()}`, values.header);
  color(`tier-${id.toLowerCase()}-background`, values.background);
}
for (const [id, values] of Object.entries(RARITY_TOKENS)) {
  color(`rarity-${id}`, values.DEFAULT);
  color(`rarity-${id}-foreground`, values.foreground);
}
for (const [id, values] of Object.entries(ITEM_TOKENS)) {
  color(`item-${id}`, values.DEFAULT);
  color(`item-${id}-foreground`, values.foreground);
}
const gradients = Object.entries(RARITY_GRADIENTS).map(([id, value]) => {
  const declaration = `  background-image: ${value};`;
  const formatted =
    declaration.length <= 80
      ? declaration
      : `  background-image: linear-gradient(\n    ${value
          .slice("linear-gradient(".length, -1)
          .split(", ")
          .join(",\n    ")}\n  );`;
  return `@utility bg-${id} {\n${formatted}\n}`;
});
const css = `/* Generated by scripts/generate-game-palette.mjs; edit src/config/gameColors.ts. */\n@theme inline {\n${colors.join("\n")}\n}\n\n${gradients.join("\n\n")}\n`;
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== css) {
    throw new Error("Game palette CSS drifted; run npm run styles:generate.");
  }
} else {
  await writeFile(target, css);
}
